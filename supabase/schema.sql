-- 9. ADMIN HELPER PROCEDURE
-- Usage: select public.assign_user_role('your_email@gmail.com', 'super_admin');
create or replace function public.assign_user_role(target_email text, new_role public.app_role)
returns text language plpgsql security definer as $$
declare
  target_uid uuid;
begin
  select id into target_uid from auth.users where email = target_email;
  if target_uid is null then
    return 'Error: User with email ' || target_email || ' does not exist in auth.users. Please sign up or create the user first in Supabase Auth.';
  end if;

  insert into public.user_roles (user_id, role)
  values (target_uid, new_role)
  on conflict (user_id, role) do update set role = new_role;

  return 'Success: Assigned ' || new_role::text || ' to ' || target_email;
end;
$$;


