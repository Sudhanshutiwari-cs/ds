-- 6. CUSTOM ACCESS TOKEN HOOK (INJECT CLAIMS INTO JWT)
create or replace function public.custom_access_token_hook(event jsonb)
returns jsonb language plpgsql stable security definer as $$
declare
  claims jsonb;
  user_role public.app_role;
  v_batch_id uuid;
  v_team_id uuid;
  v_user_id uuid;
begin
  v_user_id := (event->>'user_id')::uuid;

  -- Pick highest authority role if multiple exist
  select role into user_role 
  from public.user_roles 
  where user_id = v_user_id
  order by case role 
    when 'super_admin' then 1
    when 'manager' then 2
    when 'batch_leader' then 3
    when 'team_leader' then 4
    else 5 end
  limit 1;

  -- Fetch intern scope if assigned
  select batch_id, team_id into v_batch_id, v_team_id
  from public.interns 
  where user_id = v_user_id;

  claims := coalesce(event->'claims', '{}'::jsonb);
  claims := jsonb_set(claims, '{user_role}', to_jsonb(coalesce(user_role::text, 'individual')));
  claims := jsonb_set(claims, '{batch_id}', to_jsonb(coalesce(v_batch_id::text, 'null')));
  claims := jsonb_set(claims, '{team_id}', to_jsonb(coalesce(v_team_id::text, 'null')));

  event := jsonb_set(event, '{claims}', claims);
  return event;
end;
$$;

-- Grant permissions for Supabase Auth to execute this hook
grant usage on schema public to supabase_auth_admin;
